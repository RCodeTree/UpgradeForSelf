/* 
    详细解释：
    1. ptr1[-1]:
       - &a 是整个数组的地址。
       - &a + 1 步长是整个数组的大小(16字节)，指向数组后的内存位置。
       - (int*)(&a + 1) 强转为 int* 指针。
       - ptr1[-1] 相当于 *(ptr1 - 1)，即回退一个 int (4字节)，指向 a[3]，值为 4。

    2. *ptr2 (涉及小端存储):
       - (int)a + 1: 将地址强转为整数并加 1，实际上是地址值加了 1 个字节。
         (注意：在64位系统下将指针转为int可能会截断，建议使用 (char*)a + 1 获取字节偏移)
       - ptr2 指向 a 的起始地址 + 1字节的位置。
       
    内存分布 (小端存储 Little Endian: 低位字节存低地址):
    a[0] = 1 (0x00000001) -> 内存: 01 00 00 00
    a[1] = 2 (0x00000002) -> 内存: 02 00 00 00
    
    地址偏移:    +0  +1  +2  +3  +4  +5  +6  +7
    内存数据:    01  00  00  00  02  00  00  00
                    ^
                    |
                  ptr2 指向这里 (+1位置)
    
    ptr2 是 int*，向后读取 4 个字节:
    读出的字节序列: 00 00 00 02
    
    按小端模式还原为 int:
    低地址 00 -> 最低位
           00
           00
    高地址 02 -> 最高位
    
    结果: 0x02000000 (十六进制) -> 33554432 (十进制)
*/
#include <stdio.h>
int main()
{
    int a[4] = { 1, 2, 3, 4 };
    int* ptr1 = (int*)(&a + 1);
    int* ptr2 = (int*)((int)a + 1);

    printf("%x, %x\n", ptr1[-1], *ptr2); // 4, 2000000
    
    return 0;
}
