#include <stdio.h>

/* 
这段 C 语言代码演示了 printf 函数中一个特殊的格式化用法：使用 * 作为字段宽度说明符。这意味着字段的宽度不是固定写在格式字符串中的，而是由 printf 的一个参数动态提供的

printf("##%*d\n", i, i);

这是第一个 printf 调用。
"##%*d\n" 是格式控制字符串：
##：会直接输出两个井号。
%*d：这是一个整数格式化占位符。
*：表示字段宽度将由 printf 的下一个参数提供。
d：表示要打印一个十进制整数。
\n：表示换行符，打印完当前内容后光标会移动到下一行的开头。
i, i 是提供给 printf 的参数：
第一个 i（值为 1）会作为 * 所代表的字段宽度。
第二个 i（值为 1）是实际要打印的整数。
输出分析：此时 i 为 1。所以 printf 会打印一个宽度为 1 的整数 1。由于 1 本身就占 1 个字符，所以不会有额外的填充。
预期输出：##1
i++;

i 的值增加 1。现在 i 的值为 2。
printf("##%*d\n", i, i);

这是第二个 printf 调用。
i 的当前值为 2。
第一个 i（值为 2）作为字段宽度。
第二个 i（值为 2）是实际要打印的整数。
输出分析：printf 会打印一个宽度为 2 的整数 2。由于 2 只占 1 个字符，为了达到宽度 2，会在 2 的左侧填充一个空格（默认右对齐）。
预期输出：## 2 (注意 2 前面有一个空格)
i++;

i 的值增加 1。现在 i 的值为 3。
printf("##%*d\n", i, i);

这是第三个 printf 调用。
i 的当前值为 3。
第一个 i（值为 3）作为字段宽度。
第二个 i（值为 3）是实际要打印的整数。
输出分析：printf 会打印一个宽度为 3 的整数 3。由于 3 只占 1 个字符，为了达到宽度 3，会在 3 的左侧填充两个空格。
预期输出：## 3 (注意 3 前面有两个空格)
*/

int main() {
    int i = 1;
    printf("##%*d\n", i, i);
    i++;
    printf("##%*d\n", i, i);
    i++;
    printf("##%*d\n", i, i);

    /* 
    输出：
    ##1
    ## 2
    ##  3
    */

    return 0;
}