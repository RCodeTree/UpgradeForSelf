#include <stdio.h>

/* 
   解析 scanf("%4c%4c", &a, &b) 的行为：
   1. %4c 表示从输入流中连续读取 4 个字符。
   2. 但是，由于 a 和 b 只是单个 char 变量（只占 1 字节），这种写法会导致内存越界（Buffer Overflow）。
      它会试图把 4 个字符写到 &a 开始的内存中，a 只拿到这 4 个字符中的第 1 个字符。
      其余 3 个字符会覆盖 a 后面的内存区域（极其危险）。

   示例：输入 "123A123B"
   - 第一个 %4c 读取 "123A" -> a 拿到 '1'（即首字符），'2','3','A' 被消耗或溢出。
   - 第二个 %4c 读取 "123B" -> b 拿到 '1'（即首字符），'2','3','B' 被消耗或溢出。
   - 结果：a='1', b='1'，取不到 A 和 B。

   正确获取 A 和 B 的方法（输入 123A123B）：
   scanf("%*3c%c%*3c%c", &a, &b);
   // %*3c 表示读取 3 个字符并丢弃（跳过），%c 读取第 4 个字符赋值给变量。
*/
int main() {
    char a, b;
    scanf("%4c%4c", &a, &b); // 正确获取 A 和 B：A123B123
    printf("%c\t%c", a, b);
    return 0;
}