#include <stdio.h>
int main()
{
    /* 
    逻辑操作符：
    && 逻辑与（与）
    || 逻辑或（或）
    */
    // 逻辑操作符只关注操作数的逻辑值(即真和假)，不关注二进制
    // && 逻辑与（与）：如果两个操作数都为真，则结果为真；否则为假 ----> 当左边操作数为假时，右边操作数不再计算
    // || 逻辑或（或）：如果两个操作数有一个为真，则结果为真；否则为假 ----> 当左边操作数为真时，右边操作数不再计算

    // 示例
    int i = 0, a = 0, b = 2, c = 3, d = 4;
    i = a++ && ++b && d++;
    // i = a++ || ++b || d++;
    printf("a = %d\n b = %d\n c = %d\n d = %d\n", a, b, c, d); // a = 1, b = 2, c = 3, d = 4
    
    return 0;
}