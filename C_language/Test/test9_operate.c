// 交换两个整数，不允许使用临时变量
#include <stdio.h>
int main()
{
    /* 
     3 ^ 3 = 0 ----> 相同的数求异或结果为0
     0 ^ 5 = 5 ----> 0与任何数求异或结果为该数本身

     3 ^ 3 ^ 5 = 5 ----> 任何数与0求异或结果为该数本身
     3 ^ 5 ^ 3 = 5 ----> 异或操作符具有交换律
    */

     int a = 3;
     int b = 5;

     printf("交换前 a = %d, b = %d\n", a, b);
     a = a ^ b;
     b = a ^ b;
     a = a ^ b;
     printf("交换后 a = %d, b = %d\n", a, b);
 
}