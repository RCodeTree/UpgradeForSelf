#include <stdio.h>
int main( )
{

/* 
- %d 用于打印有符号十进制整数。
- printf 会将接收到的 int 类型的 -4 解释为有符号数，并直接打印其十进制值。
- 输出 ： dec=-4
- oct=%o ：

- %o 用于打印无符号八进制整数。
- printf 会将接收到的 int 类型的 -4 的 补码 解释为无符号数，并将其转换为八进制。
- -4 的 32 位补码是 1111 1111 1111 1111 1111 1111 1111 1100 。
- 将其转换为八进制（每 3 位一组，从右往左）： 111 111 111 111 111 111 111 111 111 100 7   7   7   7   7   7   7   7   7   4
- 输出 ： oct=37777777774 (注意：这里是 32 位 int 的八进制表示，如果 int 是 16 位，结果会不同)
- hex=%x ：

- %x 用于打印无符号十六进制整数。
- printf 会将接收到的 int 类型的 -4 的 补码 解释为无符号数，并将其转换为十六进制。
- -4 的 32 位补码是 1111 1111 1111 1111 1111 1111 1111 1100 。
- 将其转换为十六进制（每 4 位一组，从右往左）： 1111 1111 1111 1111 1111 1111 1111 1100 F    F    F    F    F    F    F    C
- 输出 ： hex=fffffffc
- unsigned=%u ：

- %u 用于打印无符号十进制整数。
- printf 会将接收到的 int 类型的 -4 的 补码 解释为无符号数，并将其转换为十进制。
- 这个 32 位的补码 1111 1111 1111 1111 1111 1111 1111 1100 对应的无符号十进制值是 2^32 - 4 。
- 2^32 是 4294967296 。
- 4294967296 - 4 = 4294967292 。
- 输出 ： unsigned=4294967292
*/

    short i;

    i = -4;
    printf("\ni: dec=%d, oct=%o, hex=%x, unsigned=%u\n", i,i,i,i);
    return 0;
}