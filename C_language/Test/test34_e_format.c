#include <stdio.h>

int main() {
    /* 
    %e 格式： 
    - %e ：将浮点数以科学计数法（小写 e）输出。
    - %.ne ：指定输出的小数位数为 n。
    - %m.ne ：指定输出的总宽度为 m，小数位数为 n。
    - %-m.ne ：指定输出的总宽度为 m，小数位数为 n，左对齐。
    - 输出：e+ 或 e- 表示指数部分的符号，即 10 的指数为正时为 +，指数为负时为 -。
    */

    /* 
    %g (通用形式)
    - 作用 ： %g 是一个“通用”的浮点数格式说明符，它会根据数值的大小 自动选择 使用 %f (定点小数形式) 或 %e (科学计数法形式) 来输出。
    - 选择规则 ：
    - 如果数字的指数小于 -4 或者大于或等于精度值（默认是 6），则使用 %e 格式。
    - 否则，使用 %f 格式。
    - 简单来说 ：对于非常小或非常大的数字， %g 会倾向于使用 %e ；对于“正常范围”内的数字，它会倾向于使用 %f 。
    - 精度 ：
    - %g 的精度 .n 表示 总的有效数字位数 （包括小数点前的数字），而不是小数点后的位数。
    - 它会 移除尾随的零 。例如， 1.230000 会被打印成 1.23 。
    - 如果结果是整数，小数点也会被移除（除非你使用了 # 标志）。
    - 特点 ：
    - 旨在提供最简洁、最易读的浮点数表示。
    - 会自动去除不必要的尾随零。
    - 在大多数情况下， %g 是打印浮点数的首选，因为它能智能地选择最佳格式。
    */

    int x = 10; 
    float pi = 3.1416;

    printf("(1) %d\n", x); // (1) 10
    printf("(2) %6d\n", x); // (2) 空格空格空格空格10
    printf("(3) %f\n", 56.1); // (3) 56.100000
    printf("(4) %14f\n", pi); // (4) 空格空格空格空格空格空格3.141600
    printf("(5) %e\n", 568.1); // (5) 5.681000e+02
    printf("(6) %14e\n", pi); // (6) 空格空格空格3.141600e+00
    printf("(7) %g\n", pi); // (7) 3.1416
    printf("(8) %12g\n", pi); // (8) 空格空格空格空格空格空格3.1416


    return 0;
}