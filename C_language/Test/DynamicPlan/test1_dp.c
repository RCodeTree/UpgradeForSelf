#include <stdio.h>

// 网格大小
#define ROW 10
#define COL 10

struct S
{
    int n;
    char m;
    double x;
};

/**
 * @brief 动态规划：计算从网格的左上角到右下角的路径总数(图中(5×5)有b, a, B, C四个点，其中文字内容是：b走到a有2条路；b走到B有3条路；用C程序求b走到C有几条路)
 *
 * @return int 0
 */
int main()
{
    /*
    1. 坐标系建立与题目分析
    观察你图片中的网格，这是一个由5×5个小方格组成的矩阵。点都在网格的交点上。
    我们以出发点b为坐标原点(0,0)，向右为x轴正方向，向下为y轴正方向：
    - b点: 坐标(0,0)。
    - a点: 向右1格，向下1格，坐标(1,1)。
    - B点: 向右2格，向下1格，坐标(2,1)。
    - C点: 在右下角，向右5格，向下5格，坐标(5,5)。
    题目规定只能向右或向下走。
    
    从b(0,0)到a(1,1)，需要走1步右、1步下，共2步。排列方式有“右下”和“下右”2种，符合图中“2条路”。
    
    从b(0,0)到B(2,1)，需要走2步右、1步下，共3步。路线数等于从3步中选1步向下的组合数，即C₃¹=3条路，符合图意。
    
    求解目标: 从b(0,0)到C(5,5)有几条路?
    
    2. 核心原理: 递推 (动态规划)
    要走到网格中的任意一点(i,j)，因为只能向右或向下移动，所以到达(i,j)的最后一步，必然是
    从它的左边(i-1,j)过来，或者是从它的上边(i,j-1)过来。
    
    因此，到达某一点的路径总数，等于到达它左边那点的路径数，加上到达它上边那点的路径数。
    
    - 状态转移方程: dp[i][j] = dp[i-1][j] + dp[i][j-1]
    - 边界条件: 网格的最上边一行 (只能一直向右走) 和最左边一列 (只能一直向下走)，路径数都是1。
     */
    // 网格的宽度和高度（以格数计）
    int m = 5;
    int n = 5;

    // dp数组，dp[i][j]表示从起点到坐标(i,j)的路径总数
    // 因为坐标最大是5，所以数组大小声明为6x6 (即 0~5)
    int dp[6][6];

    // 1. 初始化边界条件
    // 最左边一列，只能一直向下走，路径只有1条
    for (int i = 0; i <= m; i++)
    {
        dp[i][0] = 1;
    }
    // 最上面一行，只能一直向右走，路径只有1条
    for (int j = 0; j <= n; j++)
    {
        dp[0][j] = 1;
    }

    // 2. 使用递推公式计算其余各个点的路径数
    for (int i = 1; i <= m; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            // 当前点的路径数 = 上方点的路径数 + 左方点的路径数
            dp[i][j] = dp[i - 1][j] + dp[i][j - 1];
            printf("dp[%d][%d] = %d\n", i, j, dp[i][j]);
        }
    }

    // 3. 输出到达终点 (5,5) 的路径数
    printf("从 b 走到 C 的路径总数为: %d 条\n", dp[m][n]);

    printf("%llu\n", sizeof(struct S));
    return 0;
}
