#include <stdio.h>

/** brief: 分解质因数
 * 功能：分解质因数
 * 输入：一个整数num
 * 输出：num的质因数分解结果
 */
int main() {
    int n, i;
    // 获取用户输入
    // printf("请输入一个正整数: "); // 题目未明确要求提示语，但为了交互友好通常会加，也可以不加直接scanf
    // 为了严格符合“打印出 90=...”的格式，我们先读入
    if (scanf("%d", &n) != 1 || n <= 0) {
        // 简单的错误处理，题目未要求可忽略
        return 0;
    }

    printf("%d=", n);

    // 从最小的质数2开始尝试除
    for (i = 2; i <= n; i++) {
        // 只要 n 能被 i 整除，就不断地除以 i，并打印 i
        while (n % i == 0) {
            printf("%d", i);
            n = n / i; // 更新 n 为商

            // 如果 n 还没除尽（变为1），说明后面还有因数，打印乘号
            if (n > 1) {
                printf("*");
            }
        }
    }

    // 换行
    printf("\n");

    return 0;
}
