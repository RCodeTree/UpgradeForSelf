// 题目：给定 long y = -43456，依次输出：
//   printf("y=%-8ld\n", y);
//   printf("y=%-08ld\n", y);
//   printf("y=%08ld\n", y);
//   printf("y=%+8ld\n", y);
// 要求：理解并比较 %ld 的宽度与标志（-、0、+）的效果。
// 说明：
// - ld：以 long 的十进制整数格式输出。
// - 数字前的宽度（例如 8）表示“最少占用的字符数”。如果实际字符数不足，就用空格或 0 填充到该宽度。
// - '-'（左对齐）：把数字靠左放，右侧用空格补齐；有 '-' 时，'0' 标志会被忽略。
// - '0'（零填充）：在右对齐时用 0 替代左侧的空格进行填充；若有负号，则负号占一位，0 会在负号之后填充。
// - '+'（显示符号）：对正数也显示 '+'；负数仍显示 '-'；与宽度一起使用时，仍是右对齐，左侧补空格。
// 提示：y = -43456 的打印长度是 6（包含 '-' 和 5 位数字），宽度 8 时需要补 2 个位置。

#include <stdio.h>

int main(void)
{
    long y = -43456;

    // 为了直观看到空格的位置，下面在每一行的末尾加一个竖线 '|' 作为边界标记。
    // 你可以把 '|' 之前看不见的部分理解为空格或 0。

    // 1) %-8ld：左对齐，宽度 8，空位用空格填充。在 y=-43456 后面补 2 个空格。
    //    实际输出形如：y=-43456  |（两个空格在 6 位数字后面）
    printf("示例1: 格式 \"%%-8ld\" —— 左对齐，空位用空格填充\n");
    printf("输出: y=%-8ld|\n", y);

    // 2) %-08ld：同时出现 '-' 与 '0' 时，'0' 会被忽略，仍然按左对齐用空格补齐。
    //    因此与 %-8ld 的效果一致：y=-43456  |
    printf("\n示例2: 格式 \"%%-08ld\" —— 有 '-' 时，'0' 被忽略，效果与 \"%%-8ld\" 相同\n");
    printf("输出: y=%-08ld|\n", y);

    // 3) %08ld：右对齐，宽度 8，空位用 0 填充；负号占 1 位，剩余位置用 0 补足。
    //    y 的长度是 6，所以需要补 2 个 0，负号在最左侧，0 在负号之后：y=-0043456|
    printf("\n示例3: 格式 \"%%08ld\" —— 右对齐，空位用 0 填充；负号在最左侧，0 在负号之后\n");
    printf("输出: y=%08ld|\n", y);

    // 4) %+8ld：显示符号并右对齐。对负数来说仍显示 '-'；宽度 8，不足部分左侧补空格。
    //    需要补 2 个空格，因此：y=  -43456|
    printf("\n示例4: 格式 \"%%+8ld\" —— 显示符号并右对齐，左侧用空格补齐\n");
    printf("输出: y=%+8ld|\n", y);

    // 总结（用 '□' 表示空格，方便和试题对照）：
    // %-8ld   -> y=-43456□□
    // %-08ld  -> y=-43456□□
    // %08ld   -> y=-0043456
    // %+8ld   -> y=□□-43456

    return 0;
}